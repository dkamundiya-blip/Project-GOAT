class TransformedBinaryFeature(CompositeFeature):
    """Composite feature wrapper generated by a binary transformation operator."""

    def __init__(
        self,
        p1: BaseFeature,
        p2: BaseFeature,
        op_name: str,
        op_func: Any,
        math_def: str,
        algorithmic_spec: str,
    ) -> None:
        self._op_func = op_func
        name = f"{op_name}_{p1.name}_{p2.name}"
        super().__init__(
            upstream_features=[p1, p2],
            name=name,
            version="1.0.0",
            taxonomy_category=TaxonomyCategory.COMPOSITE,
            taxonomy_subcategory=f"binary_{op_name.lower()}",
            mathematical_definition=math_def,
            algorithmic_spec=algorithmic_spec,
            expected_stationarity=StationarityType.STATIONARY,
        )

    def compute(self, context: MarketDataWindow) -> np.ndarray:
        out1 = self._upstream_features[0].compute(context)
        out2 = self._upstream_features[1].compute(context)
        return self._op_func(out1, out2)

    def to_ast_dict(self) -> dict[str, Any]:
        return {
            "op": self._name,
            "parents_ast": [f.to_ast_dict() for f in self._upstream_features],
            "version": self._version,
        }

    def _get_input_requirements(self) -> dict[str, Any]:
        reqs1 = self._upstream_features[0]._get_input_requirements()
        reqs2 = self._upstream_features[1]._get_input_requirements()
        min_bars = max(reqs1.get("min_bars", 1), reqs2.get("min_bars", 1))
        cols = list(set(reqs1.get("required_columns", [])) | set(reqs2.get("required_columns", [])))
        return {"min_bars": min_bars, "required_columns": cols}


class RatioTransform(BaseTransformation):
    """Ratio transformation: f1 / max(|f2|, epsilon)."""

    def __init__(self) -> None:
        super().__init__(
            name="RatioTransform",
            version="1.0.0",
            scientific_description="Relative ratio construction between two feature series",
            mathematical_definition=r"f_{\text{out}} = \frac{f_1}{\max(|f_2|, \epsilon)}",
        )

    def transform(self, parents: list[BaseFeature]) -> BaseFeature:
        if len(parents) != 2:
            raise ValueError("RatioTransform requires exactly 2 parent features")
        p1, p2 = parents[0], parents[1]
        return TransformedBinaryFeature(
            p1=p1,
            p2=p2,
            op_name="Ratio",
            op_func=lambda a, b: a / np.maximum(np.abs(b), EPSILON),
            math_def=r"\frac{" + p1.metadata.mathematical_definition + r"}{\max(|" + p2.metadata.mathematical_definition + r"|, \epsilon)}",
            algorithmic_spec=f"{p1.name} / max(abs({p2.name}), 1e-12)",
        )


