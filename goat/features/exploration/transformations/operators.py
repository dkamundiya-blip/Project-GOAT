class RollingMeanTransform(BaseTransformation):
    """Rolling mean temporal transformation over window N."""

    def __init__(self, window: int = 10) -> None:
        self._window = window
        super().__init__(
            name=f"RollingMean_{window}",
            version="1.0.0",
            scientific_description=f"Rolling temporal mean over window N={window}",
            mathematical_definition=r"\text{EMA}_N(f)",
            parameters={"window": window},
        )

    def transform(self, parents: list[BaseFeature]) -> BaseFeature:
        if len(parents) != 1:
            raise ValueError("RollingMeanTransform requires exactly 1 parent feature")
        p = parents[0]
        w = self._window

        def compute_mean(arr: np.ndarray) -> np.ndarray:
            if len(arr) == 0:
                return np.array([], dtype=np.float64)
            res = np.zeros_like(arr, dtype=np.float64)
            for i in range(len(arr)):
                start = max(0, i - w + 1)
                res[i] = np.mean(arr[start : i + 1])
            return res

        return TransformedUnaryFeature(
            parent=p,
            op_name=f"RollMean{w}",
            op_func=compute_mean,
            math_def=r"\text{Mean}_{" + str(w) + r"}(" + p.metadata.mathematical_definition + r")",
            algorithmic_spec=f"rolling_mean({p.name}, window={w})",
            lookback_window=w,
        )


class RollingStdDevTransform(BaseTransformation):
    """Rolling standard deviation temporal transformation over window N."""

    def __init__(self, window: int = 10) -> None:
        self._window = window
        super().__init__(
            name=f"RollingStdDev_{window}",
            version="1.0.0",
            scientific_description=f"Rolling temporal volatility dispersion over window N={window}",
            mathematical_definition=r"\sigma_N(f)",
            parameters={"window": window},
        )

    def transform(self, parents: list[BaseFeature]) -> BaseFeature:
        if len(parents) != 1:
            raise ValueError("RollingStdDevTransform requires exactly 1 parent feature")
        p = parents[0]
        w = self._window

        def compute_std(arr: np.ndarray) -> np.ndarray:
            if len(arr) == 0:
                return np.array([], dtype=np.float64)
            res = np.zeros_like(arr, dtype=np.float64)
            for i in range(len(arr)):
                start = max(0, i - w + 1)
                sub = arr[start : i + 1]
                res[i] = np.std(sub) if len(sub) > 1 else 0.0
            return res

        return TransformedUnaryFeature(
            parent=p,
            op_name=f"RollStd{w}",
            op_func=compute_std,
            math_def=r"\sigma_{" + str(w) + r"}(" + p.metadata.mathematical_definition + r")",
            algorithmic_spec=f"rolling_std({p.name}, window={w})",
            lookback_window=w,
        )
