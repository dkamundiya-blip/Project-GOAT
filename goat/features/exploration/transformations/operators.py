class TransformedUnaryFeature(DerivedFeature):
    """Derived feature wrapper generated by a unary transformation operator."""

    def __init__(
        self,
        parent: BaseFeature,
        op_name: str,
        op_func: Any,
        math_def: str,
        algorithmic_spec: str,
        lookback_window: int = 1,
    ) -> None:
        self._parent = parent
        self._op_func = op_func
        name = f"{op_name}_{parent.name}"
        super().__init__(
            lookback_window=lookback_window,
            name=name,
            version="1.0.0",
            taxonomy_category=parent.metadata.taxonomy_category,
            taxonomy_subcategory=f"transformed_{op_name.lower()}",
            mathematical_definition=math_def,
            algorithmic_spec=algorithmic_spec,
            dependencies=[parent.feature_id],
            expected_stationarity=parent.metadata.expected_stationarity,
        )

    def compute(self, context: MarketDataWindow) -> np.ndarray:
        parent_out = self._parent.compute(context)
        return self._op_func(parent_out)

    def to_ast_dict(self) -> dict[str, Any]:
        return {
            "op": self._name,
            "parent_ast": self._parent.to_ast_dict(),
            "version": self._version,
        }

    def _get_input_requirements(self) -> dict[str, Any]:
        reqs = self._parent._get_input_requirements()
        reqs["min_bars"] = max(reqs.get("min_bars", 1), self._lookback_window)
        return reqs


class LogTransform(BaseTransformation):
    """Logarithmic transformation: ln(|f| + epsilon)."""

    def __init__(self) -> None:
        super().__init__(
            name="LogTransform",
            version="1.0.0",
            scientific_description="Logarithmic transformation smoothing exponential variance",
            mathematical_definition=r"f_{\text{out}} = \ln(|f_{\text{in}}| + \epsilon)",
        )

    def transform(self, parents: list[BaseFeature]) -> BaseFeature:
        if len(parents) != 1:
            raise ValueError("LogTransform requires exactly 1 parent feature")
        p = parents[0]
        return TransformedUnaryFeature(
            parent=p,
            op_name="Log",
            op_func=lambda arr: np.log(np.abs(arr) + EPSILON),
            math_def=r"\ln(|" + p.metadata.mathematical_definition + r"| + \epsilon)",
            algorithmic_spec=f"np.log(np.abs({p.name}) + 1e-12)",
        )


